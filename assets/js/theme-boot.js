/* ТАКТ — тема до первой отрисовки.
   Подключается в <head>, до разбора <body>: иначе страница успевает
   посчитать стили в дневной теме, и у того, кто выбрал ночную, сначала
   мелькает белый экран, а при reduced-motion цвета ещё и «переезжают»
   через переход. Отдельным файлом — CSP запрещает инлайн-скрипты. */
try {
  if (localStorage.getItem('takt:theme') === 'night') document.documentElement.dataset.theme = 'night';
} catch (e) { /* инкогнито: остаёмся в дневной теме */ }
